  ('Ламинирование ресниц DOUBLE - LAMI', 50, 2)
on conflict do nothing;

-- 3. Рабочие окна мастера
create table if not exists public.work_windows (
  id bigint generated by default as identity primary key,
  date date not null,
  start_time time not null,
  end_time time not null,
  comment text,
  created_at timestamptz not null default now(),
  check (end_time > start_time)
);
create index if not exists idx_work_windows_date on public.work_windows(date);

-- 4. Записи
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  client_id uuid not null references public.profiles(id) on delete cascade,
  date date not null,
  start_time time not null,
  end_time time not null,
  service_id bigint not null references public.services(id),
  service_name text not null,
  duration_min smallint not null,
  status text not null default 'active' check (status in ('active', 'completed', 'cancelled', 'no_show')),
  comment text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  cancelled_at timestamptz
);
create index if not exists idx_bookings_date_status on public.bookings(date, status);
create index if not exists idx_bookings_client on public.bookings(client_id);

-- 5. Уведомления
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  booking_id bigint references public.bookings(id) on delete set null,
  type text not null check (type in ('new_booking', 'booking_cancelled', 'booking_changed', 'reminder_24h', 'system', 'new_guest_booking')),
  title text not null,
  text text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists idx_notifications_user_read on public.notifications(user_id, is_read);

-- Автосоздание профиля при регистрации/первом входе через OTP
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, role)
  values (new.id, lower(new.email), 'client')
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Хелпер проверки роли мастера
create or replace function public.is_master()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'master' and status = 'active'
  );
$$;


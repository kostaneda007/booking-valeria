-- Функция: создание гостевой записи
create or replace function public.create_guest_booking(
    p_name text,
    p_phone text,
    p_email text default null,
    p_service_id bigint,
    p_date date,
    p_start_time time,
    p_comment text default ''
)
returns table (booking_id uuid, confirmation_code text)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_booking_id uuid;
    v_confirmation_code text;
    v_service public.services%rowtype;
    v_end_time time;
    v_text text;
    v_master_id uuid;
begin
    -- проверка, что услуга существует и активна
    select * into v_service
    from public.services
    where id = p_service_id and is_active = true;

    if not found then
        raise exception 'Услуга не найдена или неактивна';
    end if;

    -- вычислим окончание приема
    v_end_time := (p_date + p_start_time + (v_service.duration_min || ' minutes')::interval)::time;

    -- сгенерируем 6-символьный код подтверждения
    v_confirmation_code := substring(md5(random()::text), 1, 6);

    -- создадим запись
    insert into public.guest_bookings (
        name, phone, email, service_id, date, start_time, end_time,
        status, confirmation_code, comment
    ) values (
        p_name, p_phone, p_email, p_service_id, p_date, p_start_time,
        v_end_time, 'pending', v_confirmation_code, coalesce(trim(p_comment), '')
    ) returning id into v_booking_id;

    -- текст уведомления для мастера
    v_text := format(
        E'Новый гостевый запрос.\nИмя: %s\nТелефон: %s\nУслуга: %s\nДата: %s, время: %s–%s',
        p_name, p_phone, v_service.name,
        to_char(p_date, 'DD.MM.YYYY'),
        to_char(p_start_time, 'HH24:MI'),
        to_char(v_end_time, 'HH24:MI')
    );

    -- оповещение мастеру
    select id into v_master_id from public.profiles where role = 'master' limit 1;
    if v_master_id is not null then
        insert into public.notifications (user_id, type, title, text)
        values (v_master_id, 'new_guest_booking', 'Новый гостевой запрос', v_text);
    end if;

    return query select v_booking_id, v_confirmation_code;
end;
$$;

-- Функция: подтверждение гостевой записи мастером
create or replace function public.confirm_guest_booking(p_booking_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
    if not public.is_master() then
        raise exception 'Только мастер может подтверждать гостевые запросы';
    end if;

    update public.guest_bookings
    set status = 'confirmed', updated_at = now()
    where id = p_booking_id and status = 'pending';

    if not found then
        raise exception 'Запись не найдена или уже обработана';
    end if;
end;
$$;

-- Функция: получение списка ожидающих гостевых запросов для мастера
create or replace function public.get_pending_guest_bookings()
returns table (
    id uuid,
    name text,
    phone text,
    email text,
    service_id bigint,
    service_name text,
    date date,
    start_time time,
    end_time time,
    confirmation_code text,
    comment text
)
language sql
security definer
set search_path = public
as $$
    select
        gb.id,
        gb.name,
        gb.phone,
        gb.email,
        gb.service_id,
        s.name as service_name,
        gb.date,
        gb.start_time,
        gb.end_time,
        gb.confirmation_code,
        gb.comment
    from public.guest_bookings gb
    join public.services s on s.id = gb.service_id
    where gb.status = 'pending'
    order by gb.created_at desc;
$$;


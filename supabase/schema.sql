-- RPC: расчёт свободных слотов (шаг 10 минут, минимум +2 часа от текущего времени)
create or replace function public.get_available_slots(
  p_date date,
  p_service_id bigint,
  p_ignore_booking_id bigint default null
)
returns table(slot_time text)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_duration smallint;
  v_now_local timestamp := (now() at time zone 'Europe/Kaliningrad') + interval '2 hours';
  v_win record;
  v_t timestamp;
  v_end timestamp;
  v_overlap boolean;
  v_overlap_guest boolean;
begin
  select duration_min into v_duration
  from public.services
  where id = p_service_id and is_active = true;

  if v_duration is null then
    return;
  end if;

  for v_win in
    select start_time, end_time
    from public.work_windows
    where date = p_date
    order by start_time
  loop
    v_t := p_date + v_win.start_time;
    while (v_t + (v_duration || ' minutes')::interval) <= (p_date + v_win.end_time) loop
      if v_t >= v_now_local then
        v_end := v_t + (v_duration || ' minutes')::interval;
        select exists (
          select 1 from public.bookings b
          where b.date = p_date
            and b.status = 'active'
            and (p_ignore_booking_id is null or b.id <> p_ignore_booking_id)
            and v_t < (b.date + b.end_time)
            and v_end > (b.date + b.start_time)
        ) into v_overlap;

        select exists (
          select 1 from public.guest_bookings gb
          where gb.date = p_date
            and gb.service_id = p_service_id
            and gb.status <> 'cancelled'
            and v_t < (gb.date + gb.end_time)
            and v_end > (gb.date + gb.start_time)
        ) into v_overlap_guest;

        if not v_overlap and not v_overlap_guest then
          slot_time := to_char(v_t, 'HH24:MI');
          return next;
        end if;
      end if;
      v_t := v_t + interval '10 minutes';
    end loop;
  end loop;
end;
$$;

-- RPC: атомарное создание записи клиентом (с защитой от гонки)
create or replace function public.create_booking(
  p_service_id bigint,
  p_date date,
  p_start_time time,
  p_comment text default ''
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_profile public.profiles%rowtype;
  v_service public.services%rowtype;
  v_end_time time;
  v_slot_ok boolean;
  v_booking_id bigint;
  v_master_id uuid;
  v_text text;
begin
  if v_uid is null then
    raise exception 'Требуется авторизация';
  end if;

  select * into v_profile from public.profiles where id = v_uid;
  if v_profile.status = 'blocked' then
    raise exception 'Ваш профиль заблокирован';
  end if;

  -- Блокировка на дату, чтобы исключить одновременную запись на один слот
  perform pg_advisory_xact_lock(hashtext(p_date::text));

  select exists (
    select 1 from public.get_available_slots(p_date, p_service_id) s
    where s.slot_time = to_char(p_start_time, 'HH24:MI')
  ) into v_slot_ok;

  if not v_slot_ok then
    raise exception 'К сожалению, это время уже занято. Пожалуйста, выберите другое время.';
  end if;

  select * into v_service from public.services where id = p_service_id and is_active = true;
  v_end_time := (p_date + p_start_time + (v_service.duration_min || ' minutes')::interval)::time;

  insert into public.bookings (
    client_id, date, start_time, end_time, service_id, service_name, duration_min, comment
  ) values (
    v_uid, p_date, p_start_time, v_end_time, v_service.id, v_service.name, v_service.duration_min, coalesce(trim(p_comment), '')
  ) returning id into v_booking_id;

  v_text := format(
    E'Вы записаны на прием к мастеру Валерии.\n\nДата: %s\nВремя: %s–%s\nУслуга: %s\n\nОтмена возможна не позднее чем за 2 часа до начала приема.',
    to_char(p_date, 'DD.MM.YYYY'),
    to_char(p_start_time, 'HH24:MI'),
    to_char(v_end_time, 'HH24:MI'),
    v_service.name
  );

  insert into public.notifications (user_id, booking_id, type, title, text)
  values (v_uid, v_booking_id, 'new_booking', 'Вы записаны на прием', v_text);

  select id into v_master_id from public.profiles where role = 'master' limit 1;
  if v_master_id is not null then
    insert into public.notifications (user_id, booking_id, type, title, text)
    values (
      v_master_id,
      v_booking_id,
      'new_booking',
      'Новая запись',
      format(E'Новая запись.\nКлиент: %s\nТелефон: %s\n%s', coalesce(v_profile.name, '—'), coalesce(v_profile.phone, '—'), v_text)
    );
  end if;

  return v_booking_id;
end;
$$;



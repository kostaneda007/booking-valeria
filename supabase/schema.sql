-- RPC: отмена записи клиентом (не менее чем за 2 часа)
create or replace function public.cancel_my_booking(p_booking_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_b public.bookings%rowtype;
  v_now_local timestamp := now() at time zone 'Europe/Kaliningrad';
  v_master_id uuid;
  v_text text;
begin
  if v_uid is null then
    raise exception 'Требуется авторизация';
  end if;

  select * into v_b from public.bookings
  where id = p_booking_id and client_id = v_uid and status = 'active';

  if v_b.id is null or (v_b.date + v_b.start_time) <= (v_now_local + interval '2 hours') then
    raise exception 'Отмена невозможна менее чем за 2 часа до начала приема.';
  end if;

  update public.bookings
  set status = 'cancelled', cancelled_at = now(), updated_at = now()
  where id = v_b.id;

  v_text := format(
    E'Ваша запись отменена.\n\nДата: %s\nВремя: %s–%s\nУслуга: %s',
    to_char(v_b.date, 'DD.MM.YYYY'),
    to_char(v_b.start_time, 'HH24:MI'),
    to_char(v_b.end_time, 'HH24:MI'),
    v_b.service_name
  );

  insert into public.notifications (user_id, booking_id, type, title, text)
  values (v_uid, v_b.id, 'booking_cancelled', 'Запись отменена', v_text);

  select id into v_master_id from public.profiles where role = 'master' limit 1;
  if v_master_id is not null then
    insert into public.notifications (user_id, booking_id, type, title, text)
    values (v_master_id, v_b.id, 'booking_cancelled', 'Отмена записи', E'Клиент отменил запись.\n' || v_text);
  end if;
end;
$$;
